-- Sales counter (sales.html): price list + stock, bills, and a change log.
-- Kept apart from public.entries, so sales never touch the expense split.
-- Run once in Supabase → SQL Editor. Existing data is untouched; safe to run again.
-- The prices themselves are loaded separately and never committed (this repo is public).

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sno int,
  name text not null,
  category text not null default '',
  unit text not null default '',
  cost numeric not null default 0 check (cost >= 0),        -- "Actual price" list: what we paid. Hidden on screen by default.
  floor_price numeric not null check (floor_price > 0),     -- "Price Drop" list: the lowest we can ever sell at.
  price numeric not null check (price >= floor_price),      -- customer price, shown first.
  stock int not null default 0,                             -- pieces left; paid bills take it down (trigger below)
  active boolean not null default true,
  created timestamptz not null default now()
);

create table if not exists public.bills (
  id uuid primary key default gen_random_uuid(),
  kind text not null default 'sale' check (kind in ('sale', 'free')),          -- 'free' = given away (local leaders, vendors…)
  status text not null default 'paid' check (status in ('estimate', 'paid')),  -- only 'paid' counts as a sale and takes stock
  given_to text,                       -- free only: who got it
  items jsonb not null,                -- [{product_id, name, category, unit, qty, price, floor_price, cost}]
  list_total numeric not null,         -- at customer prices
  floor_total numeric not null,        -- at lowest prices
  cost_total numeric not null default 0,
  amount numeric not null,             -- what the customer pays (0 when free)
  level text,                          -- 'Customer price', '5% off', … 'Other amount' or 'Free'
  pay_mode text not null default 'cash' check (pay_mode in ('cash', 'upi')),
  collected_by text not null,
  note text,
  date date not null default current_date,   -- day of the sale (set again when an estimate is paid)
  paid_at timestamptz,
  added_by text,
  created timestamptz not null default now(),
  constraint bills_not_below_lowest check (kind = 'free' or (amount >= floor_total and amount > 0)),
  constraint bills_free_has_receiver check (kind = 'sale' or (amount = 0 and coalesce(given_to, '') <> ''))
);

-- Every change to a bill or an item is recorded here by the database itself (the app can only read it).
create table if not exists public.sales_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  by_user text,
  what text not null,                  -- 'bill' or 'item'
  ref text not null,                   -- bill id / product id
  action text not null,                -- e.g. 'sold', 'estimate', 'marked paid', 'edited', 'deleted', 'stock changed'
  before jsonb,
  after jsonb
);

create or replace function public.sales_user() returns text language sql stable as $$
  select coalesce(split_part(auth.jwt() ->> 'email', '@', 1), 'admin')
$$;

-- Stock follows paid bills only: undo the old bill's effect, then apply the new one.
-- Covers new sales, estimates being paid, edits and deletes. Two phones billing at once can't miscount.
create or replace function public.bills_stock() returns trigger language plpgsql as $$
declare it jsonb;
begin
  if tg_op in ('UPDATE', 'DELETE') and old.status = 'paid' then
    for it in select * from jsonb_array_elements(old.items) loop
      update public.products set stock = stock + (it->>'qty')::int where id = (it->>'product_id')::bigint;
    end loop;
  end if;
  if tg_op in ('INSERT', 'UPDATE') and new.status = 'paid' then
    for it in select * from jsonb_array_elements(new.items) loop
      update public.products set stock = stock - (it->>'qty')::int where id = (it->>'product_id')::bigint;
    end loop;
  end if;
  return null;
end $$;
drop trigger if exists bills_stock on public.bills;
create trigger bills_stock after insert or update or delete on public.bills for each row execute function public.bills_stock();

create or replace function public.bills_log() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.sales_log (by_user, what, ref, action, before, after) values (
    public.sales_user(), 'bill', coalesce(new.id, old.id)::text,
    case tg_op
      when 'INSERT' then case when new.kind = 'free' then 'given free' when new.status = 'paid' then 'sold' else 'estimate' end
      when 'DELETE' then 'deleted'
      else case when old.status = 'estimate' and new.status = 'paid' then 'marked paid' else 'edited' end
    end,
    case when tg_op <> 'INSERT' then to_jsonb(old) end,
    case when tg_op <> 'DELETE' then to_jsonb(new) end);
  return null;
end $$;
drop trigger if exists bills_log on public.bills;
create trigger bills_log after insert or update or delete on public.bills for each row execute function public.bills_log();

create or replace function public.products_log() returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- stock moves caused by bills are already logged on the bill; log only hand edits and new items
  if tg_op = 'UPDATE' and pg_trigger_depth() > 1 then return null; end if;
  insert into public.sales_log (by_user, what, ref, action, before, after) values (
    public.sales_user(), 'item', coalesce(new.id, old.id)::text,
    case tg_op when 'INSERT' then 'item added' when 'DELETE' then 'item deleted'
      else case when old.stock is distinct from new.stock and (old.price, old.floor_price, old.cost, old.name) = (new.price, new.floor_price, new.cost, new.name)
        then 'stock changed' else 'item edited' end end,
    case when tg_op <> 'INSERT' then to_jsonb(old) end,
    case when tg_op <> 'DELETE' then to_jsonb(new) end);
  return null;
end $$;
drop trigger if exists products_log on public.products;
create trigger products_log after insert or update or delete on public.products for each row execute function public.products_log();

alter table public.products enable row level security;
alter table public.bills enable row level security;
alter table public.sales_log enable row level security;
drop policy if exists "partners can do everything" on public.products;
create policy "partners can do everything" on public.products for all to authenticated using (true) with check (true);
drop policy if exists "partners can do everything" on public.bills;
create policy "partners can do everything" on public.bills for all to authenticated using (true) with check (true);
drop policy if exists "partners can read the log" on public.sales_log;
create policy "partners can read the log" on public.sales_log for select to authenticated using (true);

do $$ begin
  alter publication supabase_realtime add table public.products;
exception when duplicate_object then null; end $$;
do $$ begin
  alter publication supabase_realtime add table public.bills;
exception when duplicate_object then null; end $$;
